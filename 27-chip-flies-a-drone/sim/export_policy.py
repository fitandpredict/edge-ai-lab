"""Turn a drone policy (npz from colab/train_drone.py) into C for Chip.

usage:
  python sim/export_policy.py sim/brains/main.npz --name main
writes firmware/drone_brain/policy_<name>.h: float32 and int8 (per-output-channel) weights for the ESP32-S3,
plus the obs normalisation (subtract mean, multiply by 1/std) as two 27-float arrays.
(Copied from episode 26's exporter; the ONNX path is unused here.)
"""

import argparse
from pathlib import Path

import numpy as np
import onnx
from onnx import numpy_helper

CODE = Path(__file__).resolve().parent.parent


def load_onnx(path):
    m = onnx.load(str(path))
    init = {t.name: numpy_helper.to_array(t) for t in m.graph.initializer}
    sub = mul = None
    layers, act = [], None
    for n in m.graph.node:
        if n.op_type == "Sub" and n.input[0] == "obs":
            sub = init[n.input[1]]
        elif n.op_type == "Mul" and n.input[1] in init and n.input[1].endswith("recip:0"):
            mul = init[n.input[1]]
        elif n.op_type == "Gemm":
            layers.append((init[n.input[1]].astype(np.float32), init[n.input[2]].astype(np.float32)))
        elif n.op_type == "Sigmoid":
            act = "swish"
        elif n.op_type == "Relu":
            act = act or "relu"
    W, b = layers[-1]
    layers[-1] = (W[:, :4].copy(), b[:4].copy())
    return dict(mean=sub, recip=mul, layers=layers, act=act or "swish")


def load_npz(path):
    z = np.load(path)
    n = int(z["n_layers"])
    return dict(mean=z["obs_mean"].astype(np.float32), recip=(1.0 / z["obs_std"]).astype(np.float32),
                layers=[(z[f"W{i}"].astype(np.float32), z[f"b{i}"].astype(np.float32)) for i in range(n)],
                act=str(z["activation"]))


def c_array(name, a, ctype, fmt):
    flat = a.ravel()
    rows = [", ".join(fmt(v) for v in flat[i:i + 12]) for i in range(0, len(flat), 12)]
    return f"static const {ctype} {name}[{len(flat)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def write_header(p, path):
    L = p["layers"]
    dims = [L[0][0].shape[0]] + [W.shape[1] for W, _ in L]
    f = lambda v: f"{v:.8g}f"
    out = [
        "// Generated by sim/export_policy.py. Do not edit.\n#pragma once\n#include <stdint.h>\n",
        f"#define POLICY_N_LAYERS {len(L)}\n#define POLICY_N_OBS {dims[0]}\n",
        f"static const int POLICY_DIMS[{len(dims)}] = {{{', '.join(map(str, dims))}}};\n",
        f"#define POLICY_SWISH {1 if p['act'] == 'swish' else 0}\n",
        f"#define POLICY_PARAMS {sum(W.size + b.size for W, b in L)}\n",
        c_array("OBS_MEAN", p["mean"], "float", f),
        c_array("OBS_RECIP", p["recip"], "float", f),
    ]
    for i, (W, b) in enumerate(L):
        # stored output-major (out, in) so each output is one contiguous dot product
        Wt = np.ascontiguousarray(W.T)
        out.append(c_array(f"P_W{i}_F32", Wt, "float", f))
        out.append(c_array(f"P_B{i}", b, "float", f))
        scale = np.abs(Wt).max(axis=1) / 127.0
        scale[scale == 0] = 1.0
        q = np.clip(np.round(Wt / scale[:, None]), -127, 127).astype(np.int8)
        out.append(c_array(f"P_W{i}_I8", q, "int8_t", str))
        out.append(c_array(f"P_S{i}", scale.astype(np.float32), "float", f))
    for kind in ("F32", "I8", "S"):
        names = ", ".join(f"P_{'W' if kind != 'S' else 'S'}{i}{'_' + kind if kind != 'S' else ''}" for i in range(len(L)))
        ctype = {"F32": "float", "I8": "int8_t", "S": "float"}[kind]
        out.append(f"static const {ctype}* const POLICY_{kind}[{len(L)}] = {{{names}}};\n")
    out.append(f"static const float* const POLICY_B[{len(L)}] = {{{', '.join(f'P_B{i}' for i in range(len(L)))}}};\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))


def numpy_forward(p, obs, int8=False):
    x = (obs - p["mean"]) * p["recip"]
    for i, (W, b) in enumerate(p["layers"]):
        if int8:
            Wt = W.T
            s = np.abs(Wt).max(axis=1) / 127.0
            W = (np.clip(np.round(Wt / s[:, None]), -127, 127) * s[:, None]).T
        x = x @ W + b
        if i < len(p["layers"]) - 1:
            x = x / (1 + np.exp(-x)) if p["act"] == "swish" else np.maximum(x, 0)
    return np.tanh(x)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("src", help="policy .npz (colab/train_drone.py)")
    a.add_argument("--name", required=True)
    args = a.parse_args()
    p = load_onnx(args.src) if args.src.endswith(".onnx") else load_npz(args.src)
    L = p["layers"]
    n_params = sum(W.size + b.size for W, b in L)
    print("layers:", [W.shape for W, _ in L], "act:", p["act"], "params:", n_params,
          f"float32 {n_params * 4 / 1024:.0f} KiB, int8 {sum(W.size for W, _ in L) / 1024:.0f} KiB + scales")

    if not args.src.endswith(".onnx"):
        write_header(p, CODE / "firmware" / "drone_brain" / f"policy_{args.name}.h")
        print("wrote", f"firmware/drone_brain/policy_{args.name}.h")
        return
    npz = {"obs_mean": p["mean"], "obs_std": 1.0 / p["recip"], "n_layers": len(L),
           "activation": p["act"], "head": "tanh"}
    for i, (W, b) in enumerate(L):
        npz[f"W{i}"], npz[f"b{i}"] = W, b
    np.savez(CODE / "sim" / f"{args.name}.npz", **npz)

    import onnxruntime as rt
    s = rt.InferenceSession(args.src, providers=["CPUExecutionProvider"])
    obs = np.random.default_rng(0).normal(size=(256, 48)).astype(np.float32) * 0.5
    ref = np.vstack([s.run(["continuous_actions"], {"obs": o[None]})[0] for o in obs])
    print("max |numpy - onnx|      :", float(np.abs(numpy_forward(p, obs) - ref).max()))
    print("max |int8 sim - onnx|   :", float(np.abs(numpy_forward(p, obs, int8=True) - ref).max()))
    np.savez(CODE / "sim" / f"{args.name}_testvec.npz", obs=obs[:8], act=ref[:8])
    write_header(p, CODE / "firmware" / "drone_brain" / f"policy_{args.name}.h")
    print("wrote", f"sim/{args.name}.npz", f"firmware/drone_brain/policy_{args.name}.h")


if __name__ == "__main__":
    main()
