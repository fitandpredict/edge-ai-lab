"""Export the trained LSTM maze brain (actor only) to a C header for Chip, plus a numpy twin.

  python sim/export_brain.py models/lstm_final.zip      # writes firmware/maze_brain/policy_maze.h

On Chip the LSTM's two weight matrices are joined: gates = [W_ih | W_hh] @ [x ; h] + (b_ih + b_hh).
Layers: 0 = LSTM gates 148 -> 512, 1 = 128 -> 64 (tanh), 2 = 64 -> 4 logits.
"""

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HEADER = ROOT / "firmware" / "maze_brain" / "policy_maze.h"


def load(path):
    from sb3_contrib import RecurrentPPO
    sd = {k: v.numpy().astype(np.float32) for k, v in RecurrentPPO.load(path, device="cpu").policy.state_dict().items()}
    W0 = np.concatenate([sd["lstm_actor.weight_ih_l0"], sd["lstm_actor.weight_hh_l0"]], 1)
    b0 = sd["lstm_actor.bias_ih_l0"] + sd["lstm_actor.bias_hh_l0"]
    layers = [(W0, b0),
              (sd["mlp_extractor.policy_net.0.weight"], sd["mlp_extractor.policy_net.0.bias"]),
              (sd["action_net.weight"], sd["action_net.bias"])]
    torch_params = sum(sd[k].size for k in sd if k.startswith(("lstm_actor", "mlp_extractor.policy_net", "action_net")))
    return layers, torch_params


def quantise(W):
    s = np.maximum(np.abs(W).max(1), 1e-8) / 127.0
    return np.clip(np.round(W / s[:, None]), -127, 127).astype(np.int8), s.astype(np.float32)


class NumpyBrain:
    """Same maths as maze_brain.ino (float32 or the int8 path)."""

    def __init__(self, layers, int8=False):
        self.layers, self.int8 = layers, int8
        self.q = [quantise(W) for W, _ in layers]
        self.reset()

    def reset(self):
        self.h = np.zeros(128, np.float32)
        self.c = np.zeros(128, np.float32)

    def _dense(self, l, x):
        W, b = self.layers[l]
        if not self.int8:
            return W @ x + b
        q, s = self.q[l]
        amax = max(np.abs(x).max(), 1e-8)
        xq = np.round(x * 127 / amax).astype(np.int32)
        return (q.astype(np.int32) @ xq) * s * (amax / 127) + b

    def __call__(self, obs):
        g = self._dense(0, np.concatenate([obs, self.h]).astype(np.float32))
        sig = lambda v: 1 / (1 + np.exp(-v))
        i, f, gg, o = sig(g[:128]), sig(g[128:256]), np.tanh(g[256:384]), sig(g[384:])
        self.c = f * self.c + i * gg
        self.h = (o * np.tanh(self.c)).astype(np.float32)
        logits = self._dense(2, np.tanh(self._dense(1, self.h)))
        return logits.astype(np.float32)


def c_array(name, a, ctype, fmt, per_line=12):
    flat = a.ravel()
    rows = [", ".join(fmt(v) for v in flat[i:i + per_line]) for i in range(0, len(flat), per_line)]
    return f"static const {ctype} {name}[{len(flat)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def write_header(layers, torch_params, path=HEADER):
    f = lambda v: f"{v:.8g}f"
    i = lambda v: str(int(v))
    out = ["// Generated by sim/export_brain.py. Do not edit.\n#pragma once\n#include <stdint.h>\n",
           f"#define BRAIN_N_LAYERS {len(layers)}\n",
           f"static const int BRAIN_IN[{len(layers)}] = {{{', '.join(str(W.shape[1]) for W, _ in layers)}}};\n",
           f"static const int BRAIN_OUT[{len(layers)}] = {{{', '.join(str(W.shape[0]) for W, _ in layers)}}};\n",
           f"#define BRAIN_PARAMS {sum(W.size + b.size for W, b in layers)}\n",
           f"#define BRAIN_PARAMS_TORCH {torch_params}\n"]
    for l, (W, b) in enumerate(layers):
        q, s = quantise(W)
        out += [c_array(f"MZ_W{l}_F32", W, "float", f), c_array(f"MZ_B{l}", b, "float", f),
                c_array(f"MZ_W{l}_I8", q, "int8_t", i, 32), c_array(f"MZ_S{l}", s, "float", f)]
    n = len(layers)
    out.append(f"static const float* BRAIN_F32[{n}] = {{{', '.join(f'MZ_W{l}_F32' for l in range(n))}}};\n")
    out.append(f"static const float* BRAIN_B[{n}] = {{{', '.join(f'MZ_B{l}' for l in range(n))}}};\n")
    out.append(f"static const int8_t* BRAIN_I8[{n}] = {{{', '.join(f'MZ_W{l}_I8' for l in range(n))}}};\n")
    out.append(f"static const float* BRAIN_S[{n}] = {{{', '.join(f'MZ_S{l}' for l in range(n))}}};\n")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))


def check_against_torch(path, layers):
    """Run the sb3 policy and the numpy twin on the same episode; the actions must match."""
    sys.path.insert(0, str(HERE))
    from maze import MazeEnv
    from sb3_contrib import RecurrentPPO
    model = RecurrentPPO.load(path, device="cpu")
    env = MazeEnv(sizes=(7,), seed=123)
    twin = NumpyBrain(layers)
    obs, _ = env.reset()
    state, start, worst, same, n = None, np.ones(1, bool), 0.0, 0, 0
    done = trunc = False
    while not (done or trunc):
        a, state = model.predict(obs, state=state, episode_start=start, deterministic=True)
        start = np.zeros(1, bool)
        logits = twin(obs)
        same += int(np.argmax(logits) == int(a))
        n += 1
        obs, _, done, trunc, _ = env.step(int(a))
    return same, n


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "models" / "lstm_final.zip")
    layers, torch_params = load(path)
    write_header(layers, torch_params)
    p = sum(W.size + b.size for W, b in layers)
    print(f"actor params: torch {torch_params} ({torch_params * 4 / 1000:.1f} kB float32), on Chip {p} "
          f"({p * 4 / 1024:.1f} KiB float32, {p / 1024:.1f} KiB int8) -> {HEADER}")
    same, n = check_against_torch(path, layers)
    print(f"numpy twin picks the same action as PyTorch on {same}/{n} decisions")


if __name__ == "__main__":
    main()
